def main():
    """Generate both theme files"""
    home = Path.home()

    # Generate Neovim theme
    nvim_path = home / ".config" / "nvim" / "colors" / "sunnyday.lua"
    nvim_content = generate_neovim_theme()

    nvim_path.parent.mkdir(parents=True, exist_ok=True)
    nvim_path.write_text(nvim_content)
    print(f"✓ Generated Neovim theme: {nvim_path}")

    # Generate Zed theme
    zed_path = home / ".config" / "zed" / "themes" / "sunnyday.json"
    zed_content = generate_zed_theme()

    zed_path.parent.mkdir(parents=True, exist_ok=True)
    zed_path.write_text(zed_content)
    print(f"✓ Generated Zed theme: {zed_path}")

    print(f"\nTheme '{THEME_NAME}' generated successfully!")
    print("Reload your editors to see the changes.")


if __name__ == "__main__":
    main()
